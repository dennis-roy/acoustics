#include "stream_frame.h"
#include <string.h>

int main(void) {
    const uint8_t expected[] = {
        0x41, 0x43, 0x4f, 0x55, 0x01, 0x02, 0x01, 0x00,
        0x04, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x01, 0x00, 0x00, 0x00,
        0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
        0xa0, 0x86, 0x01, 0x00, 0x00, 0x00, 0x00, 0x00,
        0x7b, 0x00, 0x38, 0xfe, 0x95, 0xbf, 0x38, 0xa1,
    };
    uint8_t frame[sizeof(expected)];
    const int16_t pcm[] = {123, -456};
    size_t size = stream_frame(frame, STREAM_DATA, STREAM_SYNTHETIC, 1, 1, 0, 100000, 0, pcm, 2);
    return size != sizeof(expected) || memcmp(frame, expected, sizeof(expected)) != 0;
}
